#!/usr/bin/env node
/**
 * 产品文档「单文件 → 产品文件夹」机械迁移
 *
 * X/<分类>/<型号>.md        → X/<分类>/<型号>/index.md
 * X/<型号>.md（根级，如配件） → X/<型号>/index.md
 * 同时写入产品级 _category_.json（label 取 frontmatter title）
 *
 * 用法：node scripts/migrate-to-product-folders.js [--dry-run]
 * 范围：三条产品线的 current 与 versioned 快照；intro.md / _index.md 不动
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const LINES = [
  'sensors_docs',
  'modules_docs',
  'accessories_docs',
  path.join('sensors_versioned_docs', 'version-1.0.0'),
  path.join('modules_versioned_docs', 'version-1.0.0'),
  path.join('accessories_versioned_docs', 'version-1.0.0'),
];

const dryRun = process.argv.includes('--dry-run');

function walkMd(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walkMd(p));
    else if (e.isFile() && e.name.endsWith('.md') && e.name !== 'intro.md' && e.name !== '_index.md') {
      out.push(p);
    }
  }
  return out;
}

function readTitle(mdPath) {
  const head = fs.readFileSync(mdPath, 'utf8').split('---')[0] || '';
  const m = head.match(/^title:\s*"([^"]+)"/m) || head.match(/^title:\s*(.+)$/m);
  return (m ? m[1] : path.basename(mdPath, '.md')).trim();
}

let moved = 0, skipped = 0;

for (const line of LINES) {
  const lineDir = path.join(ROOT, line);
  if (!fs.existsSync(lineDir)) {
    console.log(`⚠️ 跳过（不存在）: ${line}`);
    continue;
  }
  const files = walkMd(lineDir);
  for (const f of files) {
    const base = path.basename(f, '.md');
    const destDir = path.join(path.dirname(f), base);
    const dest = path.join(destDir, 'index.md');
    if (fs.existsSync(destDir) || fs.existsSync(dest)) {
      skipped++;
      console.log(`⏭️ 已存在，跳过: ${path.relative(ROOT, f)}`);
      continue;
    }
    const title = readTitle(f);
    const relFile = path.relative(ROOT, f);
    if (dryRun) {
      console.log(`[dry] ${relFile} → ${path.relative(ROOT, dest)}`);
      continue;
    }
    fs.mkdirSync(destDir, { recursive: true });
    execSync(`git mv "${path.relative(ROOT, f)}" "${path.relative(ROOT, dest)}"`, { cwd: ROOT, stdio: 'pipe' });
    // 产品级 _category_.json：控制侧边栏 label；含 index.md 时 autogenerated 自动把分类链到 index 文档
    fs.writeFileSync(
      path.join(destDir, '_category_.json'),
      JSON.stringify({ label: title, collapsed: false, collapsible: true }, null, 2) + '\n'
    );
    moved++;
    console.log(`✅ ${relFile} → ${path.relative(ROOT, dest)}（label: ${title}）`);
  }
}

console.log(`\n${dryRun ? '[dry-run] ' : ''}完成：移动 ${moved} 个，跳过 ${skipped} 个`);
